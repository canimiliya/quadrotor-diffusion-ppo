def test_r2_source_has_no_diffusion_teacher_or_premature_test_dataset_access():
    source = (ROOT / "scripts" / "run_s4r2_ppo.py").read_text(encoding="utf-8").lower()
    assert "quadrotor_diffusion_ppo.diffusion" not in source
    assert "quadrotor_diffusion_ppo.expert" not in source
